#!/usr/bin/env python3
"""Extract provisional circular CIR-shape descriptors from ESP32-S3 20MHz LLTF CSI.

Only relative descriptors: NOT calibrated first path delays / NLOS classification.
The CSI in this experiment is downlink UDP reply CSI, not FTM-frame CSI.
"""
import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np


def features_from_hex(csi_hex: str, first_word_invalid: int):
    b = bytes.fromhex(csi_hex)
    if len(b) != 128:
        return None  # 64 complex int8 pairs
    interleaved = np.frombuffer(b, dtype=np.int8).astype(float)
    H = interleaved[1::2] + 1j * interleaved[0::2]  # real + j*imag
    if first_word_invalid:
        H[:2] = 0
    cir = np.fft.ifft(H)
    power = np.abs(cir)**2
    total = float(np.sum(power))
    if not np.isfinite(total) or total <= 0:
        return None
    p = power / total
    n = len(p)
    peak = int(np.argmax(p))
    # An IFFT is PERIODIC: bin 63 is one bin BEFORE bin 0, not 63 bins AFTER.
    # This signed circular lag avoids the false long-delay spread generated by
    # treating 0..63 as an ordinary nonperiodic sequence.
    lag = (np.arange(n) - peak + n // 2) % n - n // 2
    mean_lag = float(np.dot(lag, p))
    rms_bins = float(np.sqrt(np.dot((lag - mean_lag)**2, p)))
    entropy = float(-np.sum(p[p > 0]*np.log(p[p > 0]))/np.log(n))
    return {
        'peak_bin': peak,
        'peak_ratio': float(p[peak]),
        'circular_rms_spread_bins': rms_bins,
        'offpeak_energy_outside_2_bins': float(np.sum(p[np.abs(lag) > 2])),
        'normalized_energy_entropy': entropy,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', default='recordings')
    parser.add_argument('--output', default='results/cir_features_fixed.csv')
    parser.add_argument('--round-output', default='results/cir_round_features_fixed.csv')
    args = parser.parse_args()
    packet_fields = ['trial','condition','true_distance_m','round_id','t_us',
                     'rssi_dbm','first_word_invalid', 'peak_bin', 'peak_ratio',
                     'circular_rms_spread_bins', 'offpeak_energy_outside_2_bins',
                     'normalized_energy_entropy']
    numeric = ['peak_ratio','circular_rms_spread_bins',
               'offpeak_energy_outside_2_bins','normalized_energy_entropy']
    output=Path(args.output); output.parent.mkdir(parents=True,exist_ok=True)
    rout=Path(args.round_output); rout.parent.mkdir(parents=True,exist_ok=True)
    groups = defaultdict(list)
    kept, rejected = 0, 0
    with output.open('w',encoding='utf-8-sig',newline='') as dst:
        writer=csv.DictWriter(dst,fieldnames=packet_fields)
        writer.writeheader()
        for meta_file in sorted(Path(args.root).rglob('metadata.json')):
            folder=meta_file.parent
            path=folder/'csi.csv'
            if not path.exists():continue
            meta=json.loads(meta_file.read_text(encoding='utf-8-sig'))
            with path.open('r',encoding='utf-8-sig',newline='') as src:
                for row in csv.DictReader(src):
                    feat=features_from_hex(row['csi_hex'],int(row['first_word_invalid']))
                    if feat is None:
                        rejected+=1
                        continue
                    prefix={'trial':meta['trial'], 'condition':meta['condition'],
                            'true_distance_m':meta['true_distance_m'],
                            'round_id':row['round_id'],'t_us':row['t_us'],
                            'rssi_dbm':row['rssi_dbm'],
                            'first_word_invalid':row['first_word_invalid']}
                    writer.writerow({**prefix,**feat})
                    groups[(meta['trial'],row['round_id'])].append(feat)
                    kept+=1
    rf=['trial','round_id','csi_count']+numeric
    with rout.open('w', encoding='utf-8-sig',newline='') as dst:
        writer=csv.DictWriter(dst, fieldnames=rf)
        writer.writeheader()
        for (trial,rid), rows in sorted(groups.items(),key=lambda x:(x[0][0],int(x[0][1]))):
            writer.writerow({'trial':trial,'round_id':rid,'csi_count':len(rows),
                            **{k:float(np.mean([r[k] for r in rows])) for k in numeric}})
    print('Packets processed:',kept,'invalid length/empty CSI:',rejected)
    print('Unique CSI rounds:',len(groups))
    print('Saved:',output, 'and',rout)
    print('WARNING: features are relative circular CIR-shape descriptors, not physical calibrated path delay.')

if __name__=='__main__':
    main()
